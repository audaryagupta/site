export function LinkIcon({
  icon,
  size = 22,
  className = "",
}: {
  icon: string;
  size?: number;
  className?: string;
}) {
  // Uploaded custom icon (a stored image URL).
  if (icon && (icon.startsWith("/") || icon.startsWith("http"))) {
    return (
      // eslint-disable-next-line @next/next/no-img-element
      <img
        src={icon}
        alt=""
        width={size}
        height={size}
        className={`rounded object-contain ${className}`}
        style={{ width: size, height: size }}
      />
    );
  }
  const brand = BRAND[icon];
  if (brand) {
    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="currentColor"
        className={className}
        aria-hidden
      >
        <path d={brand} />
      </svg>
    );
  }
  const Lucide = LUCIDE[icon] || LinkIconLucide;
  return <Lucide size={size} className={className} />;
}
